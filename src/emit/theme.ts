/** Writes the theme as `themePart` and makes it `masterPart`'s theme; each master gets its own copy. */
export function emitOwnTheme(pkg: OpcPackage, masterPart: string, themePart: string): void {
  pkg.addRelationship(masterPart, REL.theme, path.posix.relative(path.posix.dirname(masterPart), themePart));
  pkg.addPart(themePart, CT.theme, serialize(parseXml(THEME_XML)));
}
